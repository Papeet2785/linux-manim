from manim import * 
class linux(Scene):
    def construct(self):
        tux = ImageMobject(r"assets/tux.png").scale(0.2)
        debian = ImageMobject(r"assets/debian.png").scale(0.127).shift(RIGHT*21.5, UP*2.5)
        arch = ImageMobject(r"assets/arch.png").scale(0.5).shift(RIGHT*18.5, UP*2.5)
        fedora = ImageMobject(r"assets/fedora.png").scale(0.4).shift(RIGHT*20)
        temple = ImageMobject(r"assets/temple.png").scale(0.5)
        nixos = ImageMobject(r"assets/nixos.png").scale(0.5).shift(UP*2)
        t1 = Text("Why Bother with the rest,")
        t2 = Text("when you can work on the best!")
        t3 = Text("The only 3 that you need ...").shift(DOWN*1.6)
        t4 = Text("Pick one.")
        t5 = Text("Stable, but current.").shift(DOWN*1)
        t6 = Text("You won't get updates, and").shift(DOWN*1)
        t7 = Text(" it just works!!!").shift(DOWN*2)
        t8 = Text("You can install anything, ").shift(DOWN*1)
        t9 = Text("and you can break anything!").shift(DOWN*2)
        t10 = Text("Choose one based on your needs").shift(UP*2)
        t11 = Text("They have varying degrees of stability,").shift(UP*1)
        t12 = Text("but they are expansive enough to have a")
        t13 = Text("large community each.").shift(DOWN*1)
        t14 = Text("but, if its hard to decide ...").shift(DOWN*2)
        t15 = Text("Made by Papeet2785").shift(UP*0.5)
        t16 = Text("in Linux", color=YELLOW).shift(DOWN*0.5)
        t17 = Text("in NixOS", color=BLUE).shift(DOWN*0.5)
        self.play(FadeIn(tux), FadeIn(debian), FadeIn(arch), FadeIn(fedora))
        self.play(tux.animate.shift(LEFT*5))
        self.play(Write(t1.shift(RIGHT*1.5, UP*0.5)), Write(t2.shift(DOWN*0.5, RIGHT*1.5)))
        self.play(t1.animate.shift(LEFT*20), t2.animate.shift(LEFT*20), tux.animate.shift(LEFT*20), debian.animate.shift(LEFT*20), arch.animate.shift(LEFT*20), fedora.animate.shift(LEFT*20))
        self.play(Write(t3))
        self.play(FadeOut(t3), debian.animate.shift(RIGHT*2, DOWN*0.5), arch.animate.shift(LEFT*2, DOWN*0.5), fedora.animate.shift(UP*2), FadeOut(t3))
        self.play(Write(t4))       
        self.play(FadeOut(t4), debian.animate.shift(RIGHT*20).scale(2), arch.animate.shift(LEFT*20).scale(2), fedora.animate.scale(2))
        self.play(Write(t5))
        self.play(debian.animate.shift(LEFT*23), fedora.animate.shift(LEFT*20), t5.animate.shift(LEFT*20))
        self.play(Write(t6))
        self.play(Write(t7))
        self.play(arch.animate.shift(RIGHT*23.5), FadeOut(t6, t7), debian.animate.shift(RIGHT*23), fedora.animate.shift(RIGHT*30))
        self.play(Write(t8))
        self.play(Write(t9))
        self.play(FadeOut(arch, t8, t9))
        self.play(Write(t10))
        self.play(Write(t11))
        self.play(Write(t12))
        self.play(Write(t13))
        self.wait(0.5)
        self.play(Write(t14), run_time = 1.5)
        self.play(FadeOut(t10, t11, t12, t13, t14), FadeIn(temple), run_time = 2)
        self.play(temple.animate.scale(4), run_time = 2)
        self.play(FadeOut(temple))
        self.play(Write(t15))
        self.play(Write(t16))
        self.play(FadeIn(nixos))
        self.play(Transform(t16, t17))
        self.wait(1)
